NARROW = {'I': 3, '1': 3, '!': 1, '.': 1, "'": 2, ' ': 3}


def glyph(ch):
    g = np.array([[c == '1' for c in row] for row in GLYPHS[ch]])
    if ch in NARROW:
        cols = np.where(g.any(axis=0))[0]
        if len(cols):
            g = g[:, cols.min():cols.max() + 1]
        else:
            g = g[:, :NARROW[ch]]
    return g


def render(text, gap=1):
    """Boolean (7, width) image of `text`."""
    parts = []
    for ch in text.upper():
        parts.append(glyph(ch))
        parts.append(np.zeros((7, gap), dtype=bool))
    return np.hstack(parts[:-1]) if parts else np.zeros((7, 0), dtype=bool)
